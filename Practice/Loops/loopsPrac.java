package Practice.Loops;

public class loopsPrac 
{
    public static void learnLoops()
    {
        int num = 17;
        for(int i = 1; i <= 10; i+=1)
        {
            System.out.println (num + " X " + i + " = " + (num * i));
            
        }
    }
    
    public static void main(String[] args) 
    {
        learnLoops();    
    }    
}
