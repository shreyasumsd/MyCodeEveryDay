package Operators;

public class Arithmetic_Oper 
{
    public static void main(String[] args) 
    {
        int a = 2;
        int b = 5;

        System.out.println(a + b); 
        System.out.println(a - b);
        System.out.println(a * b);
        System.out.println(a / b);
        System.out.println(a % b);
    }
}